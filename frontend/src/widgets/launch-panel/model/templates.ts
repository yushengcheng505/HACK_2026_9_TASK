/** Шаблон эпика: готовый текст, который можно взять в форму или запустить. */
export interface EpicTemplate {
  id: string
  title: string
  summary: string
  text: string
  /** Короткие метки: протокол, что приложено. */
  tags: string[]
}

/** Склеивает строки, разорванные переносом в исходном markdown, — абзацы и пункты списка остаются. */
export const unwrap = (text: string) =>
  text
    .split('\n')
    .reduce<string[]>((lines, line) => {
      const prev = lines.at(-1)
      const joins = prev && line.trim() && !/^\s*[-*]\s/.test(line) && !prev.trimEnd().endsWith(':')
      if (joins) lines[lines.length - 1] = `${prev.trimEnd()} ${line.trim()}`
      else lines.push(line)
      return lines
    }, [])
    .join('\n')

